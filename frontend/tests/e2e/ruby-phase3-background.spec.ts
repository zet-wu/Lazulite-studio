import { expect, test, type Page } from '@playwright/test';
import { importLyrics } from '../fixtures/import-lyrics';
import { backgroundPhase3 } from '../fixtures/background-phase3';
async function load(page: Page) {
  await page.goto('/projects/sample-project/edit');
  await importLyrics(page, { name: 'background.ttml', mimeType: 'application/xml', buffer: Buffer.from(backgroundPhase3) });
  await expect(page.locator('main section[data-line-id="L1-bg"]')).toBeVisible();
}
test('background editing, mixed singer selection, relation and generation use explicit rows', async ({ page }) => {
  await load(page);
  const bg = page.locator('main section[data-line-id="L1-bg"]'), main = page.locator('main section[data-line-id="L1"]');
  const bgOutline = page.locator('[data-line-id="L1-bg"] > [data-outline-drag]'), mainOutline = page.locator('[data-line-id="L1"] > [data-outline-drag]');
  await bgOutline.click();
  await expect(page.getByRole('checkbox', { name: '歌手 Backing', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: '歌手 Main', exact: true })).not.toBeChecked();
  await page.getByRole('checkbox', { name: '歌手 Main', exact: true }).check();
  await mainOutline.click(); await expect(page.getByRole('checkbox', { name: '歌手 Backing', exact: true })).not.toBeChecked();
  await page.getByRole('checkbox', { name: '歌手 Main', exact: true }).uncheck();
  await bgOutline.click(); await expect(page.getByRole('checkbox', { name: '歌手 Main', exact: true })).toBeChecked();
  await mainOutline.click({ modifiers: ['Control'] });
  await expect(page.getByText('混合值', { exact: true })).toBeVisible();
  await bgOutline.click();
  await bg.getByRole('textbox', { name: '翻译 1', exact: true }).fill('修改后的背景翻译');
  await bg.getByRole('textbox', { name: '翻译 1', exact: true }).press('Enter');
  await expect(main.getByRole('textbox', { name: '翻译 1', exact: true })).toHaveValue('主行译文');
  await bgOutline.click(); await page.getByLabel('所属主行').selectOption('L2');
  await expect(bg.getByText('L2 · 背景', { exact: true })).toBeVisible();
  await expect(bg.getByRole('textbox', { name: '翻译 1', exact: true })).toHaveValue('修改后的背景翻译');
  await expect(bg.locator('[data-romanization-unit-id]')).toHaveCount(2);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await bgOutline.click({ button: 'right' }); await page.getByRole('menuitem', { name: '生成日文罗马字音译…', exact: true }).click();
  const generation = page.getByRole('dialog', { name: '生成日文罗马字音译', exact: true });
  await generation.getByLabel('L1 · 背景生成内容').selectOption('append');
  await generation.getByRole('button', { name: '生成音译', exact: true }).click();
  await expect(bg.locator('[data-romanization-content-id]')).toHaveCount(2);
  await bg.locator('[data-romanization-content-id]').last().getByText('音译 · ja-Latn', { exact: true }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '从音译生成 注音…', exact: true }).click();
  const ruby = page.getByRole('dialog', { name: '从音译生成 注音', exact: true });
  await ruby.getByLabel('字符输出').selectOption('roman');
  await ruby.getByRole('button', { name: '生成 注音', exact: true }).click();
  await expect(ruby).toHaveCount(0);
  await expect(main.locator('[data-romanization-content-id]')).toHaveCount(1);
  await expect(page.getByText(/Lundefined/)).toHaveCount(0);
  await page.screenshot({ path: test.info().outputPath('background-editor.png') });
});
test('background content transfer and clipboard deletion preserve its parent', async ({ page }) => {
  await load(page);
  const bg = page.locator('main section[data-line-id="L1-bg"]');
  await bg.locator('[data-romanization-content-id]').getByText('音译 · ja-Latn', { exact: true }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '转移到其他歌词行…', exact: true }).click();
  const transfer = page.getByRole('dialog', { name: '转移音译内容' });
  await transfer.getByLabel('目标歌词行').selectOption('L2'); await transfer.getByRole('button', { name: '应用（一次撤销）' }).click();
  await expect(bg.locator('[data-romanization-content-id]')).toHaveCount(0);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  const content = bg.locator('[data-romanization-content-id]');
  await content.getByText('音译 · ja-Latn', { exact: true }).click(); await content.focus(); await page.keyboard.press('Delete');
  await expect(bg.locator('[data-romanization-content-id]')).toHaveCount(0);
  await expect(bg.getByRole('textbox', { name: '词 か', exact: true })).toHaveValue('か');
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await expect(bg.locator('[data-romanization-content-id]')).toHaveCount(1);
});

test('AMLL renders background sublyrics while its singer layout remains a consumer projection', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await load(page);
  await page.getByRole('button', { name: '收起时间轴', exact: true }).click();
  await page.getByRole('button', { name: 'AMLL 预览', exact: true }).click();
  const player = page.locator('.amll-lyric-player');
  await expect(player.getByText('背景译文', { exact: true })).toBeInViewport(); await expect(player).toContainText('主行译文');
  await expect(player).toContainText('ka'); await expect(player).toContainText('na');
  const geometry = await player.evaluate(el => Array.from(el.querySelectorAll('*')).filter(node => node.childElementCount === 0 && ['主行译文', '背景译文'].includes(node.textContent ?? '')).map(node => ({ text: node.textContent, x: node.getBoundingClientRect().x, width: node.getBoundingClientRect().width, parentClass: node.parentElement?.className })));
  const { writeFile } = await import('node:fs/promises');
  await writeFile(test.info().outputPath('background-preview.json'), JSON.stringify(geometry, null, 2));
  await page.screenshot({ path: test.info().outputPath('background-preview.png') });
});
