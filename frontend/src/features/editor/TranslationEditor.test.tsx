import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { createLyricDocument, plainTranslation } from '../../domain/lyric-document';
import { TranslationEditor } from './TranslationEditor';
import { TranslationTrackDialog } from './TranslationTrackDialog';
import { type LyricCommand, applyLyricCommand } from '../../domain/lyric-commands';
beforeEach(() => vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} }));
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it('defaults to the first track and submits text without local language overrides', () => {
  const document = createLyricDocument('行'), apply = vi.fn((_command: LyricCommand) => true);
  document.translationTracks = [{ id: 'a', language: 'en', purpose: 'subtitle', contents: [] }];
  render(<TranslationEditor document={document} lineId={document.lines[0].id} apply={apply} />);
  expect(screen.getByLabelText('新增翻译的轨道')).toHaveValue('a');
  fireEvent.change(screen.getByLabelText('新增翻译的轨道'), { target: { value: 'a' } });
  fireEvent.click(screen.getByRole('button', { name: '新增翻译' }));
  const text = screen.getByLabelText('翻译 1'); fireEvent.change(text, { target: { value: ' song ' } }); fireEvent.blur(text);
  expect(apply).toHaveBeenCalledWith(expect.objectContaining({ type: 'insert-translation-content', trackId: 'a', content: expect.objectContaining({ text: ' song ', lineId: document.lines[0].id }) }));
});
it('applies active metadata edits once, validates language and blocks stale document proposals', () => {
  const document = createLyricDocument('行'); document.translationTracks = [{ id: 'a', language: 'en', purpose: 'subtitle', contents: [plainTranslation('text', document.lines[0].id)] }];
  const apply = vi.fn(command => { applyLyricCommand(document, command); return true; });
  const props = { document, apply, close: vi.fn() }; const view = render(<TranslationTrackDialog {...props} />);
  fireEvent.change(screen.getByLabelText('翻译轨道 1语言'), { target: { value: 'en_US' } });
  fireEvent.click(screen.getByRole('button', { name: '应用' })); expect(screen.getByRole('alert')).toHaveTextContent('语言标签');
  fireEvent.change(screen.getByLabelText('翻译轨道 1语言'), { target: { value: '' } });
  fireEvent.click(screen.getByRole('button', { name: '应用' })); expect(props.close).toHaveBeenCalledOnce();
  expect(apply.mock.calls.at(-1)![0].tracks[0].language).toBeNull();
  view.rerender(<TranslationTrackDialog {...props} document={{ ...document }} />);
  expect(screen.getByRole('button', { name: '应用' })).toBeDisabled();
});
it('deletes immediately in the draft, clears target and selection, and allows cancelling without application', () => {
  const document = createLyricDocument('行'); const content = plainTranslation('text', document.lines[0].id);
  document.translationTracks = [{ id: 'a', language: 'en', purpose: 'subtitle', contents: [content] }];
  const apply = vi.fn(() => true), close = vi.fn(); render(<TranslationTrackDialog document={document} apply={apply} close={close} />);
  fireEvent.click(screen.getByLabelText(/选择翻译轨道 1 · .* · 内容 1/));
  fireEvent.change(screen.getByLabelText('翻译归轨目标'), { target: { value: 'a' } });
  fireEvent.click(screen.getByRole('button', { name: '删除轨道及 1 份内容（轨道 1）' }));
  expect(screen.getByLabelText('翻译归轨目标')).toHaveValue('');
  expect(screen.getByRole('button', { name: '转入目标轨道' })).toBeDisabled();
  expect(screen.getByText(/已选择 0 份内容/)).toBeVisible();
  fireEvent.click(screen.getByRole('button', { name: '取消' }));
  expect(close).toHaveBeenCalledOnce(); expect(apply).not.toHaveBeenCalled(); expect(document.translationTracks[0].contents).toEqual([content]);
});
it('short references keep five complete visible characters and never modify whitespace', async () => {
  const { shortReference } = await import('./TranslationTrackDialog');
  for (const text of ['', '短句', '12345', ' e\u0301👨‍👩‍👧‍👦🇨🇳字']) expect(shortReference(text)).toBe(text);
  expect(shortReference(' e\u0301👨‍👩‍👧‍👦🇨🇳字尾')).toBe(' e\u0301👨‍👩‍👧‍👦🇨🇳字…');
  expect(shortReference('123456')).toBe('12345…');
});
it('selects all content across tracks with mixed states and reports only actual moves', () => {
  const document = createLyricDocument('行'); const lineId = document.lines[0].id;
  document.translationTracks = Array.from({ length: 40 }, (_, i) => ({ id: `t${i}`, language: 'en', purpose: 'subtitle', contents: [plainTranslation(`text${i}`, lineId)] }));
  document.translationTracks.push({ id: 'empty', language: null, purpose: 'subtitle', contents: [] });
  const apply = vi.fn((_command: LyricCommand) => true); render(<TranslationTrackDialog document={document} apply={apply} close={vi.fn()} />);
  const global = screen.getByRole('checkbox', { name: '全选内容' });
  fireEvent.click(screen.getByLabelText(/选择翻译轨道 1 · .* · 内容 1/));
  expect(global).toHaveAttribute('aria-checked', 'mixed'); expect((global as HTMLInputElement).indeterminate).toBe(true);
  fireEvent.click(global); expect(global).toBeChecked();
  expect(screen.getAllByRole('checkbox', { name: '全选本轨内容' }).at(-1)).toBeDisabled();
  fireEvent.change(screen.getByLabelText('翻译归轨目标'), { target: { value: 't0' } });
  expect(screen.getByText(/实际转入 39 份，将移除 39 条/)).toBeVisible();
  fireEvent.click(screen.getByRole('button', { name: '转入目标轨道' }));
  fireEvent.click(screen.getByRole('button', { name: '应用' }));
  const command = apply.mock.calls[0][0];
  if (command.type !== 'set-translation-tracks') throw new Error('wrong command');
  const tracks = command.tracks;
  expect(tracks.map((track: { id: string }) => track.id)).toEqual(['t0', 'empty']);
  expect(tracks[0].contents).toEqual(document.translationTracks.flatMap(track => track.contents));
});

it('creates the first track atomically and cancels empty drafts without writing', () => {
  const document = createLyricDocument('行'), apply = vi.fn((_command: LyricCommand) => true);
  render(<TranslationEditor document={document} lineId={document.lines[0].id} apply={apply}/>);
  fireEvent.click(screen.getByRole('button', { name: '新增翻译' }));
  fireEvent.blur(screen.getByLabelText('翻译 1')); expect(apply).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: '新增翻译' }));
  fireEvent.change(screen.getByLabelText('翻译 1'), { target: { value: '译文' } });
  fireEvent.blur(screen.getByLabelText('翻译 1'));
  const next = applyLyricCommand(document, apply.mock.calls[0][0]);
  expect(next.translationTracks).toHaveLength(1);
  expect(next.translationTracks[0]).toMatchObject({ language: null, purpose: 'subtitle', contents: [{ text: '译文' }] });
});
it('keeps a draft when its stable target disappears and requires a new selection', () => {
  const document = createLyricDocument('行'), apply = vi.fn((_command: LyricCommand) => true);
  document.translationTracks = ['a', 'b'].map(id => ({ id, language: null, purpose: 'subtitle', contents: [] }));
  const props = { document, lineId: document.lines[0].id, apply };
  const view = render(<TranslationEditor {...props}/>);
  fireEvent.change(screen.getByLabelText('新增翻译的轨道'), { target: { value: 'b' } });
  fireEvent.click(screen.getByRole('button', { name: '新增翻译' }));
  fireEvent.change(screen.getByLabelText('翻译 1'), { target: { value: '草稿' } });
  view.rerender(<TranslationEditor {...props} document={{ ...document, translationTracks: [document.translationTracks[0]] }}/>);
  fireEvent.blur(screen.getByLabelText('翻译 1')); expect(apply).not.toHaveBeenCalled();
  expect(screen.getByLabelText('翻译 1')).toHaveValue('草稿');
  fireEvent.change(screen.getByLabelText('新增翻译的轨道'), { target: { value: 'a' } });
  fireEvent.blur(screen.getByLabelText('翻译 1')); expect(apply).toHaveBeenCalledOnce();
});
